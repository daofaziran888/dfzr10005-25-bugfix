"""示例数据：每个模块给几条不同状态的记录，方便起服务后立刻看到内容。"""
from __future__ import annotations

from typing import Any

def _retention_versions(
    snapshots: list[dict[str, Any]],
    *,
    current_index: int,
    status: str,
) -> dict[str, Any]:
    """构造保留规则的版本结构：历史版本整体冻结，当前版本承载现行状态。"""
    versions: list[dict[str, Any]] = []
    for index, snapshot in enumerate(snapshots):
        version = dict(snapshot)
        version["version"] = index + 1
        version["生效状态"] = "当前版本" if index == current_index else "历史版本"
        if index == current_index:
            version["状态"] = status
        else:
            version["状态"] = "已失效"
        versions.append(version)
    return {
        "current_version": versions[current_index],
        "versions": versions,
    }


def _retention_row(
    row_id: int,
    code: str,
    status: str,
    *,
    scope: str,
    period: str,
    snapshots: list[dict[str, Any]],
    current_index: int = 0,
) -> dict[str, Any]:
    current = snapshots[current_index]
    version_info = _retention_versions(snapshots, current_index=current_index, status=status)
    return {
        "id": row_id,
        "status": status,
        "pending": status in ("草稿", "生效中"),
        "abnormal": False,
        "规则编号": code,
        "数据集范围": scope,
        "保留期限": current["保留期限"],
        "过期动作": current["过期动作"],
        "例外清单": list(current["例外清单"]),
        "合规依据": current["合规依据"],
        "执行周期": current["执行周期"],
        "规则状态": status,
        "current_version": version_info["current_version"],
        "versions": version_info["versions"],
    }


